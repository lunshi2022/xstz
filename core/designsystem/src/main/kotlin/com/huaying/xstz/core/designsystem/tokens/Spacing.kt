package com.huaying.xstz.core.designsystem.tokens

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * 间距令牌（方案阶段 2 第 1 项）。
 *
 * ══════════════════════════════════════════════════════════════════
 * 为什么要有这一层
 *
 * 旧工程里到处是 `padding(horizontal = 120.dp)` / `offset(y = 140.dp)`
 * 这类魔数（方案风险表 C3 已点名）。魔数的真正问题不是"不好看"，
 * 而是**无法整体调整**：想统一收紧一屏的留白，得翻遍所有文件挑数字，
 * 且改完很难判断有没有漏。
 *
 * 令牌只做一件事：让"同一个语义的间距"只有一个取值来源。
 * 数量刻意压到少——尺度太多等于没有尺度，最后大家还是随手写 dp。
 * ══════════════════════════════════════════════════════════════════
 *
 * 取值依据：4dp 基准网格（Android 密度无关像素的最小可感知变化约 4dp）。
 * 命名用语义而非尺寸，是为了让调用处读起来像设计文档：
 * `Spacing.screenEdge` 比 `16.dp` 更能表达"这是屏幕左右安全边距"。
 */
object Spacing {
    /** 2dp。仅用于描边内缩、图标与文字之间的极小间隙 */
    val hairline: Dp = 2.dp

    /** 4dp。紧邻元素（图标与其标签） */
    val xxs: Dp = 4.dp

    /** 8dp。同一组内的元素间距 */
    val xs: Dp = 8.dp

    /** 12dp。列表行的内部垂直留白 */
    val sm: Dp = 12.dp

    /**
     * 16dp。**屏幕左右边距**。
     * 这是全局最常用的一个值，改这里等于改所有页面的左右留白。
     */
    val screenEdge: Dp = 16.dp

    /** 20dp。卡片内容内边距 */
    val md: Dp = 20.dp

    /** 24dp。不同区块之间 */
    val lg: Dp = 24.dp

    /** 32dp。把内容分组拉开层次 */
    val xl: Dp = 32.dp

    /** 48dp。大区块分隔、空状态上方的留白 */
    val xxl: Dp = 48.dp

    /**
     * 底部内容与 Tab 栏之间的让位。
     *
     * 实测依据：Tab 栏为悬浮胶囊，距屏幕底边 8~12dp（方案 8.4），
     * 栏高约 60dp，所以内容底部需要让出 ~88dp 才不会被遮挡。
     * 这个数不能小：滚动列表最后一项被悬浮栏压住是最常见的视觉缺陷。
     */
    val tabBarClearance: Dp = 88.dp
}
